  function readLang() {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved === 'en' || saved === 'zh') return saved;
    } catch {}
    return 'zh';
  }

  let lang = readLang();

  function t(key, vars) {
    const table = dict[lang] || dict.zh;
    let text = table[key] ?? dict.zh[key] ?? key;
    if (vars) {
      Object.entries(vars).forEach(([name, value]) => {
        text = text.split(`{${name}}`).join(String(value));
      });
    }
    return text;
  }

  function setLang(next) {
    if (next !== 'zh' && next !== 'en') return;
    lang = next;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch {}
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
    applyStaticI18n();
    window.dispatchEvent(new CustomEvent('embody:langchange', { detail: { lang } }));
  }

  function setLabeledControlText(el, value) {
    // Preserve any element children (input/select/textarea/div/…); only refresh text nodes.
    const firstElement = el.querySelector(':scope > *');
    if (!firstElement) {
      el.textContent = value;
      return;
    }
    [...el.childNodes].forEach((node) => {
      if (node.nodeType === 3) node.remove();
    });
    el.insertBefore(document.createTextNode(`${value} `), firstElement);
  }

  function setKbdButtonText(el, value) {
    const kbd = el.querySelector('kbd');
    if (!kbd) {
      el.textContent = value;
      return;
    }
    [...el.childNodes].forEach((node) => {
      if (node.nodeType === 3) node.remove();
    });
    el.insertBefore(document.createTextNode(`${value} `), kbd);
  }

  function applyStaticI18n(root = document) {
    root.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (!key) return;
      const value = t(key);
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') return;
      if (el.querySelector(':scope > kbd')) {
        setKbdButtonText(el, value);
        return;
      }
      // Never wipe nested controls / preserve blocks with textContent.
      if (el.children.length > 0) {
        setLabeledControlText(el, value);
        return;
      }
      el.textContent = value;
    });
    root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (key) el.setAttribute('placeholder', t(key));
    });
    root.querySelectorAll('[data-i18n-title]').forEach((el) => {
      const key = el.getAttribute('data-i18n-title');
      if (key) el.setAttribute('title', t(key));
    });
    root.querySelectorAll('[data-i18n-aria]').forEach((el) => {
      const key = el.getAttribute('data-i18n-aria');
      if (key) el.setAttribute('aria-label', t(key));
    });
    const langSelect = document.getElementById('langSelect');
    if (langSelect) langSelect.value = lang;
  }

  window.EmbodyI18n = {
    t,
    setLang,
    getLang: () => lang,
    applyStaticI18n,
    dict,
  };

  document.addEventListener('DOMContentLoaded', () => {
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
    applyStaticI18n();
  });
